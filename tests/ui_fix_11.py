"""Mobile navigation, focus, dismissals, and desktop details regression."""
import sys
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 390, "height": 844})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(sys.argv[1])
    page.locator('[name=username]').fill('admin')
    page.locator('[name=password]').fill('phillip-demo')
    page.locator('#login-form button').click()
    expect(page.locator('.shell')).to_be_visible()
    trigger = page.locator('[data-action=menu]')
    nav = page.locator('#primary-navigation')
    close = nav.get_by_role('button', name='Close navigation')
    details = nav.locator('.route-menu')
    expect(trigger).to_have_attribute('aria-expanded', 'false')
    assert nav.evaluate('(n) => n.inert')
    trigger.click()
    expect(trigger).to_have_attribute('aria-expanded', 'true')
    expect(page.get_by_role('dialog', name='Primary navigation')).to_be_visible()
    expect(details).to_have_attribute('open', '')
    expect(close).to_be_focused()
    page.keyboard.press('Shift+Tab')
    assert nav.evaluate('(n) => n.contains(document.activeElement)')
    page.keyboard.press('Tab')
    expect(close).to_be_focused()
    page.keyboard.press('Escape')
    expect(trigger).to_be_focused()
    expect(trigger).to_have_attribute('aria-expanded', 'false')
    assert nav.evaluate('(n) => n.inert')
    trigger.click()
    page.locator('.sidebar-backdrop').click(position={'x': 380, 'y': 800})
    expect(trigger).to_be_focused()
    trigger.click()
    close.click()
    expect(trigger).to_be_focused()
    trigger.click()
    nav.locator('[data-thread]').first.click()
    expect(trigger).to_have_attribute('aria-expanded', 'false')
    expect(trigger).to_be_focused()
    page.wait_for_url('**/chat?thread=*')
    trigger.click()
    nav.locator('.new-project').click()
    expect(page.locator('[data-project-root]')).to_be_visible()
    expect(page.locator('[data-action=menu]')).to_have_attribute('aria-expanded', 'false')
    page.locator('[data-action=menu]').click()
    page.set_viewport_size({'width': 1200, 'height': 844})
    expect(nav).not_to_have_class('menu-open')
    assert not nav.evaluate('(n) => n.inert')
    expect(details).not_to_have_attribute('open', '')
    details.locator('summary').click()
    expect(details).to_have_attribute('open', '')
    details.locator('summary').click()
    expect(details).not_to_have_attribute('open', '')
    # The pages menu lists only pages (Chat and Project are always in the sidebar) and stays open between settings pages.
    details.locator('summary').click()
    expect(details).to_have_attribute('open', '')
    assert nav.locator('.page-link[data-page=conversations], .page-link[data-page=projects]').count() == 0
    nav.locator('.page-link[data-page=personas]').click()
    expect(page.locator('#workspace')).to_have_attribute('data-page', 'personas')
    expect(details).to_have_attribute('open', '')
    nav.locator('.page-link[data-page=knowledge]').click()
    expect(page.locator('#workspace')).to_have_attribute('data-page', 'knowledge')
    expect(details).to_have_attribute('open', '')
    details.locator('summary').click()
    expect(details).not_to_have_attribute('open', '')
    page.reload()
    expect(details).not_to_have_attribute('open', '')
    page.set_viewport_size({'width': 390, 'height': 844})
    assert nav.evaluate('(n) => n.inert')
    assert not errors, errors
    print('PASS: mobile navigation and desktop details', flush=True)
    browser.close()
